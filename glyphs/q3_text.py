# Generates src/q3_text.inc from glyphs/q3_strings.txt: {stock English line, console line} pairs for the DLL's
# draw-time text swap (CoD1 / UO). Stock lines come from the games' localizedstrings/english/*.str, extracted from
# Main/localized_english_pak*.pk3 and uo/localized_english_pakuo*.pk3 into the two folders given.
# "[{cmd}]" in a stock line is already a key when drawn, so it matches like "%s".
# usage: python3 glyphs/q3_text.py <main strings dir> <uo strings dir>   (dirs holding localizedstrings/english)
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))


def load(root, name):
    out, ref = {}, None
    path = os.path.join(root, "localizedstrings", "english", name)
    for line in open(path, encoding="latin1"):
        m = re.match(r'\s*REFERENCE\s+(\S+)', line)
        if m: ref = m[1]; continue
        m = re.match(r'\s*LANG_ENGLISH\s+"(.*)"\s*$', line)
        if m and ref: out[ref] = m[1]
    return out


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(mainDir, uoDir):
    pairs, cache = {}, {}
    for line in open(os.path.join(here, "q3_strings.txt"), encoding="utf-8"):
        line = line.rstrip("\n")
        if not line or line.startswith("#"): continue
        where, name, ref, new = line.split("|", 3)
        key = (where, name)
        if key not in cache: cache[key] = load(mainDir if where == "main" else uoDir, name)
        old = re.sub(r"\[\{[^}]*\}\]", "[%s]", cache[key][ref])
        assert pairs.get(old, new) == new, (old, new)
        pairs[old] = new
    with open(os.path.join(here, "..", "src", "q3_text.inc"), "w") as f:
        f.write("// generated by glyphs/q3_text.py from glyphs/q3_strings.txt (do not edit)\n")
        for old, new in pairs.items(): f.write(f"{{{c(old)}, {c(new)}}},\n")
    print(len(pairs), "lines")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
